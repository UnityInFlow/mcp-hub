child "start --daemon forks before loading config: errors vanish, stale PID file, exit 0" "bug" \
'**Where:** `src/main.rs:35-44` (daemonize + write PID) runs before `src/main.rs:65` (`find_and_load_config`); stderr is already `/dev/null` (`src/daemon.rs:188`).

