'**Where:** `src/web/sse.rs:54-55`

The SSE log stream builds the line with `format!("<div class=\"log-line\">…{}…{}</div>", line.server, line.message)` and the HTMX SSE extension (`static/htmx-sse.js`) swaps it into the DOM as HTML. Neither field is escaped. The Askama templates are fine (auto-escape, no `|safe`) — this is the one hand-built HTML path.

