child "Crash-restart does not kill the child's process group — orphaned npx/uvx grandchildren" "bug" \
'**Where:** `src/supervisor.rs:408-424` (crash path after `child.wait()` returns), `src/supervisor.rs:149` (`child.kill()` SIGKILL escalation)

Only the graceful-shutdown path uses `killpg(SIGTERM)`. When the direct child exits on its own nothing signals the group, and the SIGKILL escalation after the 5 s timeout uses `child.kill()`, which signals only the direct child. MCP servers are almost always launched via a wrapper (`npx -y …`, `uvx …`, `node` shims): when the wrapper dies the real server survives, keeps the stdout pipe open (so `reader_task` never sees EOF), and collides with the respawn on ports/state. Group members that ignore SIGTERM survive shutdown.

**Fix:** on the crash path call `killpg(pid, SIGKILL)` (ignore `ESRCH`) before computing backoff; in the escalation path use `killpg(pid, SIGKILL)` then `child.wait()`. Add a test using `bash -c "sleep 9999 & exec sleep 0.1"` that asserts the inner `sleep` is gone after the restart.'

child "JSON-RPC id collision: server-initiated requests are parsed as responses to the hub's own requests" "bug" \
'**Where:** `src/mcp/protocol.rs:63-67` (`JsonRpcResponse { id: u64, result: Option, error: Option }`), `src/mcp/dispatcher.rs:84-89` (routing by id), `src/mcp/health.rs:34` (`ping_server`)

`JsonRpcResponse` has no `method` field and both `result` and `error` are optional, so a server-initiated request such as `{"jsonrpc":"2.0","id":3,"method":"roots/list"}` (or `sampling/createMessage`, `elicitation/create` — all real MCP server→client requests) deserialises as the reply to the hub'"'"'s own id 3. Server and client number ids independently, so collisions are routine. `ping_server` then reports Healthy on a non-response, and introspection may parse an "empty result". `ping_server` also treats `result: None, error: None` as success. String/null ids are silently discarded.

**Fix:** reject any line carrying a `method` key (it is a request/notification, not a response); require exactly one of `result`/`error`; model `id` as `serde_json::Value` or an enum. Add dispatcher tests for: server-initiated request with a colliding id, out-of-order responses, interleaved non-JSON lines, string ids.'

