child "Shutdown can skip stop_all_servers when a socket client is still connected" "bug" \
'**Where:** `src/main.rs:194` (`Arc::try_unwrap(state)`), `src/control.rs:133` (`handle_connection` spawned per client, no read timeout)

On shutdown `Arc::try_unwrap` fails if any `handle_connection` task still holds a clone of `DaemonState` — e.g. a client that connected but sent nothing. The error path then skips `stop_all_servers` and keeps the PID file, leaving child servers running.

Related stale-daemon race: `src/daemon.rs:120-127` ("PID alive but socket not connectable") removes the socket and proceeds, and `control.rs:120` unlinks whatever socket exists before bind — two daemons can start. There is also a TOCTOU window between `check_existing_daemon` and bind.

**Fix:** take the handles out from under the lock (`std::mem::take(&mut *handles.lock().await)`) instead of unwrapping the `Arc`; add a read timeout in `handle_connection`; treat an alive PID as "already running" and hold an `flock` on the PID file for the daemon'"'"'s lifetime.'

