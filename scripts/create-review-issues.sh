#!/usr/bin/env bash
# create-review-issues.sh — file the 2026-10-31 code-review findings as GitHub issues.
#
# Creates one tracking issue plus one sub-issue per finding in UnityInFlow/mcp-hub,
# using your own `gh` login. Safe to read top-to-bottom: every issue body is inline.
#
# Usage:
#   gh auth status                              # must be logged in with issues:write
#   bash scripts/create-review-issues.sh        # create everything
#   DRY_RUN=1 bash scripts/create-review-issues.sh   # print titles only, create nothing
#
# Labels used: bug, enhancement, documentation (all exist in the repo).
# Sub-issue linking uses the GraphQL addSubIssue mutation (best-effort; if it fails
# the child still carries a "Part of #<tracker>" line).
set -euo pipefail

REPO="UnityInFlow/mcp-hub"
DRY_RUN="${DRY_RUN:-0}"
FOOTER=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'

TRACKER_NUM=""
TRACKER_NODE=""
CREATED=()

# create_issue <title> <labels-csv> <body>  -> prints issue number
create_issue() {
    local title="$1" labels="$2" body="$3"
    if [ "$DRY_RUN" = "1" ]; then
        echo "[dry-run] $title  [$labels]" >&2
        echo "0"
        return
    fi
    local url
    url=$(gh issue create --repo "$REPO" --title "$title" --label "$labels" --body "$body$FOOTER")
    echo "created: $url" >&2
    echo "${url##*/}"
}

issue_node_id() {
    gh api "repos/$REPO/issues/$1" --jq .node_id
}

link_sub_issue() {
    local child_num="$1"
    [ "$DRY_RUN" = "1" ] && return 0
    local child_node
    child_node=$(issue_node_id "$child_num")
    gh api graphql -f query='
      mutation($parent: ID!, $child: ID!) {
        addSubIssue(input: { issueId: $parent, subIssueId: $child }) { issue { number } }
      }' -f parent="$TRACKER_NODE" -f child="$child_node" >/dev/null 2>&1 \
      || echo "warn: could not link #$child_num as sub-issue (body still says 'Part of #$TRACKER_NUM')" >&2
}

# child <title> <labels-csv> <body>
child() {
    local title="$1" labels="$2" body="$3"
    local num
    num=$(create_issue "$title" "$labels" "Part of #${TRACKER_NUM}.

$body")
    CREATED+=("#$num $title")
    link_sub_issue "$num"
}

