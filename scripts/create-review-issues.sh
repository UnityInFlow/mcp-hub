**Fix:** switch `handles` to `RwLock` or clone `Vec<(name, watch::Receiver)>` under a short lock; match on the enum; return 503 when overall status is `failed` (keep the JSON body). The existing `health_responds_under_100ms` test runs on empty state and is a flaky timing assertion — replace it with a test that `/health` answers while the handles lock is held by another task.'

child "Dispatcher robustness: stdin write without timeout, pending-map leak, unbounded line length, non-UTF-8 kills reader" "bug" \
'**Where:** `src/mcp/dispatcher.rs`

1. `:146-155` — `write_all`/`flush` on the shared stdin has no timeout and holds the `SharedStdin` lock across the await. If the server stops reading stdin and the pipe fills, the write blocks forever, health never reports Failed, and introspection hangs. Wrap write+flush in `tokio::time::timeout`.
2. `:136` / `:147-154` — the pending-response entry is inserted before the write and only removed on timeout, not on write/flush error. Unbounded growth if the server closed stdin but stays alive. Remove on the error path (or RAII guard).
3. `:83` and `src/supervisor.rs:85,101` — `lines()` has no maximum length; a server that emits a huge line without `\n` grows memory without bound. Use `LinesCodec::new_with_max_length` from `tokio-util` (already a dependency).
4. `:83` — `while let Ok(Some(..))` exits on any read error including invalid UTF-8, draining pending and ending routing for a live process; every later ping fails but nothing restarts on `HealthStatus::Failed` (no consumer of Failed exists outside display). Use a lossy decode, and decide what `Failed` should trigger — the spec implies restart.
5. `src/supervisor.rs:357-397` — a `run_introspection` already in flight (up to 20 s) can finish after a respawn and write capabilities for the dead process; `select!` the cancel token against the introspection future itself.'

