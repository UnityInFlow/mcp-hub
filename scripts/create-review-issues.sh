child "/health blocks on the supervisor mutex, returns 200 on 'failed', and computes status by string matching" "bug" \
'**Where:** `src/web/routes.rs:371-396` (`health_handler`)

- `state.handles.lock().await` — the comment says "non-blocking", but it is the same `tokio::Mutex<Vec<ServerHandle>>` that `handle_reload` (`src/main.rs:418`) holds across `apply_config_diff`, which awaits process shutdown (up to 5 s per server). During a reload `/health` — and every page — stalls for seconds, exactly when a monitor wants an answer.
- Overall status is derived from `s.health.starts_with("failed")` / `== "healthy"` on display strings instead of the `HealthStatus` enum.
