**Fix:**
1. Load and validate the config (and fail on zero servers) *before* `daemonize_process()`.
2. Have the parent wait on a pipe for a "socket bound / ready" byte from the child before exiting 0, and propagate a non-zero exit + the error text otherwise.
3. Remove the PID file on every error path after it is written.
Add a CLI test: `start --daemon` with a bad config exits non-zero and leaves no PID/socket file.'

child "Daemon has no log output — stdout/stderr redirected to /dev/null after fork" "bug" \
'**Where:** `src/daemon.rs:188` (`redirect_to_dev_null`), `src/supervisor.rs:94` (child stderr → `eprintln!`), all `tracing` output.

After the fork every diagnostic disappears: web-port bind failures (`main.rs:108`), reload failures (`main.rs:431`), spawn errors, backoff/Fatal transitions, and the child processes'"'"' stderr. The only way to debug a daemon today is to run it in the foreground.

**Fix:** redirect fd 1/2 to `~/.config/mcp-hub/daemon.log` (append, 0600) instead of `/dev/null`; optionally add `--log-file <path>`. Mention the path in `mcp-hub status` output when in daemon mode. Also replace `eprintln!` in the drain task with `writeln!(io::stderr())` that ignores errors — `eprintln!` panics if stderr is closed, which kills the drain and blocks the child on a full pipe.'

